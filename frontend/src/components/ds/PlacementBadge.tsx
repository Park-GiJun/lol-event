/**
 * 배치 중 표시.
 *
 * 예전에는 배치 구간이 시작되는 자리에 구분선을 깔거나(리더보드) 아예 별도 표로
 * 떼어 놓았다(플레이어 목록). 배치 중은 순위를 매기지 않아 Elo 가 거기서 다시 높은 값부터
 * 시작하는데, 그 경계가 "여기부터는 다른 표"라고 알려 주는 역할이었다.
 *
 * 다만 경계는 목록을 두 토막으로 끊어 놓는다. 검색으로 걸러 보거나 스크롤해서 아래쪽만
 * 보고 있으면 그 사람이 왜 순위가 없는지 알 길이 없었고, 같은 사람을 두 표에서 찾아야 했다.
 * 뱃지는 줄마다 붙으므로 어디서 보든 이유가 같이 읽힌다.
 *
 * 기준이 **경기 수가 아니라 라인 맞대결 수**라는 점이 특히 오해를 사기 쉬워서
 * (100경기를 뛰어도 포지션이 깨진 경기만 있으면 배치 중이다) 툴팁에 그걸 적어 둔다.
 */
export function PlacementBadge({ minDuels }: { minDuels: number }) {
  return (
    <span
      className="t-chip"
      title={`라인 맞대결 ${minDuels}회를 채우면 순위에 들어갑니다. 표본이 모자라 순위를 매기지 않습니다.`}
      style={{ marginLeft: 6, height: 20, fontSize: 11 }}
    >
      배치중
    </span>
  );
}
