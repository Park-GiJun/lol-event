package com.gijun.main.domain.service

import kotlin.math.pow

/**
 * 레이팅 상수와 순수 산식. 상태도, 저장도, 경기 개념도 없다.
 *
 * ## 왜 두 레이팅을 나눴나
 * 이 내전은 매 세션 한 사람이 포지션까지 보고 팀을 직접 짠다. 편성자가 균형을 맞추는 만큼
 * 팀 승패에 남는 것은 실력차가 아니라 **편성자의 추정 오차**다. 158경기 워크포워드 검증 결과:
 *
 * - 팀 승패로 갱신한 Elo 는 라인 결과 예측에서 무정보 기준선보다 **나빴다** (로그로스 0.6941 vs 0.6931)
 * - 라인 맞대결로 갱신한 Elo 가 **팀 승패까지도** 더 잘 맞혔다 (세션 첫 경기 0.6560 vs 0.6841)
 * - 총 K 를 고정하고 팀:라인 비중만 바꿔도 모든 구간에서 라인 100% 가 최적이었다
 *
 * 그래서 실력 레이팅(laneElo)과 전적 레이팅(teamElo)을 **별도 컬럼으로 분리**하고 둘을 하나로
 * 합치지 않는다. 섞는 순간 라인 레이팅이 편성 오차로 오염된다.
 *
 * ## 검증에서 탈락해 여기 없는 것들
 * 아래는 전부 시도했다가 더 나빠져서 뺀 것이다. 다시 넣지 마라.
 *
 * - **개인 지표 가산항(β).** 킬관여·딜지분을 포지션 표준화해 ΔR 에 더하는 방식. β > 0 인 모든
 *   조합이 β = 0 보다 나빴다. (이전 구현의 `lanePerformance` 배분 가중치가 정확히 이 형태였다.)
 * - **포지션별 산식 분리.** 튜닝 구간에서 71.8% 까지 오르지만 검증 구간에서 단순한 쪽에 졌다.
 *   포지션당 실질 표본이 39경기라 노이즈를 학습한다.
 * - **챔피언별 산식 분리.** 158종에 참가 행 1,580개. 챔피언당 평균 10행이다.
 * - **승리 폭(MOV).** 골드차를 시그모이드로 S 에 넣는 방식은 모든 스케일에서 이진 판정보다 나빴다.
 * - **진영 보정.** 블루 승률 50.6%(80/158). 보정할 게 없다.
 * - **K > 16.** 큰 K 가 좋아 보이는 건 세션 내 팀 반복 누수 때문이다. 반분 신뢰도는 K 가
 *   커질수록 단조 감소한다 (K=8 에서 0.629 → K=64 에서 0.470).
 */
object RatingMath {

    /** 신규 플레이어 시작 점수. */
    const val START = 1500.0

    /** 로지스틱 기울기. 400점 차이 = 약 10:1 기대 승률. */
    const val SCALE = 400.0

    /** 표본이 쌓인 뒤의 K. */
    const val K_BASE = 16.0

    /** 배치 구간 K. 초반에 빨리 제자리를 찾게 한다. */
    const val K_PLACEMENT = 26.0

    /** 이 횟수 미만이면 배치 구간. 라인은 대결 수, 팀은 경기 수로 센다. */
    const val PLACEMENT = 10

    /**
     * 표시값 수축의 사전 표본 수. `n / (n + PRIOR)` 이 신뢰 가중치가 된다.
     *
     * 반분 신뢰도가 0.57~0.61 이라 원값을 그대로 노출하면 표본 적은 선수가 과하게 튄다.
     * 10 은 [PLACEMENT] 와 같은 값이다 — 배치를 막 벗어난 사람이 딱 절반만 반영된다.
     */
    const val SHRINK_PRIOR = 10.0

    /** a 가 b 를 이길 기대 확률. 표준 Elo 로지스틱. */
    fun expected(a: Double, b: Double): Double =
        1.0 / (1.0 + 10.0.pow((b - a) / SCALE))

    /** 누적 횟수에 따른 K. */
    fun kFactor(count: Int): Double =
        if (count < PLACEMENT) K_PLACEMENT else K_BASE

    /**
     * **API 응답 전용** 수축 표시값. 저장은 언제나 원값으로 한다.
     *
     * 내부 계산(예측, 편성 보조, 다음 경기의 기대 승률)에는 절대 쓰지 마라 — 검증에서 더 나빴다.
     */
    fun display(elo: Double, count: Int): Double =
        START + (elo - START) * count / (count + SHRINK_PRIOR)
}
